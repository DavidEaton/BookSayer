using System.Diagnostics;
using System.Text;

namespace BookSayer;

internal sealed record Recording(string Title, IReadOnlyList<string> Files);

internal static class Audio
{
    public static async Task Assemble(string work, string output, string title, string author,
        IReadOnlyList<Recording> chapters, CancellationToken token)
    {
        static string Escape(string value) => value.Replace("\\", "\\\\").Replace("=", "\\=")
            .Replace(";", "\\;").Replace("#", "\\#").ReplaceLineEndings(" ");
        var metadata = new StringBuilder(";FFMETADATA1\n");
        metadata.AppendLine($"title={Escape(title)}").AppendLine($"artist={Escape(author)}")
            .AppendLine("genre=Audiobook").AppendLine("comment=Synthetic narration generated by BookSayer");
        long start = 0;
        foreach (var chapter in chapters)
        {
            long end = start + chapter.Files.Sum(path => new FileInfo(path).Length / 2);
            metadata.AppendLine("[CHAPTER]").AppendLine("TIMEBASE=1/24000")
                .AppendLine($"START={start}").AppendLine($"END={end}").AppendLine($"title={Escape(chapter.Title)}");
            start = end;
        }
        await File.WriteAllTextAsync(Path.Combine(work, "metadata.txt"), metadata.ToString(), token);
        await Run(work, ["-f", "s16le", "-ar", "24000", "-ac", "1", "-i", "pipe:0",
            "-f", "ffmetadata", "-i", "metadata.txt", "-map", "0:a", "-map_metadata", "1",
            "-map_chapters", "1", "-c:a", "libmp3lame", "-b:a", "96k", "-f", "mp3", output],
            chapters.SelectMany(chapter => chapter.Files), token);
    }

    public static async Task Run(string work, string[] args, IEnumerable<string>? audio, CancellationToken token)
    {
        var info = new ProcessStartInfo("ffmpeg") { WorkingDirectory = work, UseShellExecute = false,
            RedirectStandardInput = audio != null, RedirectStandardError = true };
        foreach (var arg in new[] { "-hide_banner", "-loglevel", "error", "-nostdin" }.Concat(args))
            info.ArgumentList.Add(arg);
        using var process = Process.Start(info) ?? throw new IOException("Could not launch FFmpeg.");
        using var registration = token.Register(() => { try { process.Kill(true); } catch (InvalidOperationException) { } });
        var errors = process.StandardError.ReadToEndAsync();
        IOException? pipeError = null;
        if (audio != null)
        {
            try
            {
                foreach (var file in audio)
                {
                    await using var input = File.OpenRead(file);
                    await input.CopyToAsync(process.StandardInput.BaseStream, token);
                }
            }
            catch (IOException ex) { pipeError = ex; }
            finally { process.StandardInput.Close(); }
        }
        await process.WaitForExitAsync(token);
        var message = await errors;
        if (process.ExitCode != 0) throw new IOException($"FFmpeg failed: {message.Trim()}", pipeError);
        if (pipeError != null) throw pipeError;
    }
}
